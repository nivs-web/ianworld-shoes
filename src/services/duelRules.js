/**
 * 결투 승패를 가른다.
 *
 * ★★ **순서가 곧 규칙이다.** (2026-08-27, 사용자 지정)
 *
 * *"먼저 죽으면 안됨, 죽으면 지는거야 (...) 상대방보다 오래 살아남거나,
 *   많은 금화를 먹는게 목적"*
 *
 *     ① 살아남았는가   죽은 사람이 진다. 한 명이 죽으면 판이 끝나므로
 *                      사실상 "먼저 죽은 사람이 진다" 다
 *     ② 금화           둘 다 살아서 시간이 다 됐으면 많이 주운 사람이 이긴다
 *     ③ 점수
 *     ④ uid            비기는 경우를 남기면 양쪽이 서로 다른 답을 낸다
 *
 * 예전 1순위였던 **보스 처치 수는 뺐다.** 결투가 겨루자는 값이 금화로 바뀌었다.
 *
 * @param {object} players 방의 players 노드
 * @returns {string[]} 이긴 순서대로의 uid
 */
export function duelRanking(players) {
  return Object.entries(players ?? {})
    .filter(([, p]) => p && !p.waiting)
    .map(([uid, p]) => ({
      uid,
      /* `alive` 가 아예 없는 예전 판은 살아 있는 것으로 본다 —
         없는 필드로 "죽었다" 를 판단하면 조용히 틀린다 */
      alive: p.alive === false ? 0 : 1,
      coins: p.coins | 0,
      score: p.score | 0,
    }))
    .sort((a, b) =>
      (b.alive - a.alive) ||
      (b.coins - a.coins) ||
      (b.score - a.score) ||
      (a.uid < b.uid ? -1 : 1))
    .map((r) => r.uid);
}
